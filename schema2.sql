CREATE DATABASE granthalaya;
USE granthalaya;

CREATE TABLE members (
    id VARCHAR(255) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role ENUM('Student', 'Staff') NOT NULL,
    status ENUM('Active', 'Inactive') DEFAULT 'Active',
    institution_code VARCHAR(255),
    joined_on DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE books (
    id VARCHAR(255) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    isbn VARCHAR(20),
    category VARCHAR(100),
    total_copies INT DEFAULT 1,
    shelf_location VARCHAR(50),
    condition_status ENUM('New', 'Good', 'Worn') DEFAULT 'Good'
);

CREATE TABLE transactions (
    id VARCHAR(255) PRIMARY KEY,
    book_id VARCHAR(255),
    member_id VARCHAR(255),
    issue_date DATE NOT NULL,
    due_date DATE NOT NULL,
    return_date DATE,
    status ENUM('issued', 'returned', 'overdue') NOT NULL,
    renewed TINYINT DEFAULT 0,
    fine INT DEFAULT 0,
    FOREIGN KEY (book_id) REFERENCES books(id),
    FOREIGN KEY (member_id) REFERENCES members(id)
);

CREATE TABLE book_requests (
    id VARCHAR(255) PRIMARY KEY,
    book_id VARCHAR(255),
    member_id VARCHAR(255),
    request_date DATETIME NOT NULL,
    status ENUM('Pending', 'Approved', 'Rejected') DEFAULT 'Pending',
    handled_on DATETIME,
    FOREIGN KEY (book_id) REFERENCES books(id),
    FOREIGN KEY (member_id) REFERENCES members(id)
);

